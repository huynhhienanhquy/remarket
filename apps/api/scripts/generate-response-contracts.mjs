import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const source = fileURLToPath(new URL("../../../docs/openapi.yaml", import.meta.url));
const output = fileURLToPath(new URL("../../../packages/shared/src/response-contracts.ts", import.meta.url));
const document = parse(await readFile(source, "utf8"));
const dereference = (value) => value.$ref
  ? value.$ref.slice(2).split("/").reduce((node, key) => node[key], document) : value;
const validationKeys = new Set(["$ref", "type", "nullable", "required", "properties", "items", "enum", "allOf", "anyOf", "oneOf", "pattern", "minimum", "maximum"]);
function compact(value) {
  if (Array.isArray(value)) return value.map(compact);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(Object.entries(value).filter(([key]) => validationKeys.has(key)).map(([key, item]) => [key,
    key === "properties" ? Object.fromEntries(Object.entries(item).map(([name, schema]) => [name, compact(schema)])) : compact(item)]));
}
const routes = [];
for (const [path, methods] of Object.entries(document.paths)) for (const [method, operation] of Object.entries(methods)) {
  if (!operation.responses) continue;
  for (const [status, response] of Object.entries(operation.responses)) {
    if (!status.startsWith("2")) continue;
    const schema = dereference(response).content?.["application/json"]?.schema;
    if (schema) routes.push({ path, method: method.toUpperCase(), status: Number(status), schema: compact(schema) });
  }
}
const content = "// Generated by apps/api/scripts/generate-response-contracts.mjs. Do not edit.\nconst contracts: { schemas: Record<string, unknown>; routes: Array<{ path: string; method: string; status: number; schema: unknown }> } = " + JSON.stringify({ schemas: Object.fromEntries(Object.entries(document.components.schemas).map(([key, schema]) => [key, compact(schema)])), routes }, null, 2) + ";\nexport default contracts;\n";
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== content) throw new Error("Response contracts are stale. Run pnpm --filter @remarket/api contracts:generate.");
} else await writeFile(output, content);
