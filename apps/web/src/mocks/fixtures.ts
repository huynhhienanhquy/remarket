function imageSet(productIndex: number, title: string, count: number) {
  return Array.from({ length: count }, (_, index) => ({
    id: `${IDS.product(productIndex)}-img-${index}`,
    url: placeholderImage(
      title,
      count > 1 ? `Ảnh ${index + 1}/${count} · minh họa` : "Ảnh minh họa",
    ),
    sort_order: index,
  }));
}

interface ProductSeed {
  index: number;
  seller: number;
  category: number;
  title: string;
  description: string;
  price: string;
  condition: Condition;
  usage?: number;
  province: string;
  method: DeliveryMethod;
  fee?: string;
  status?: MockProduct["status"];
  images?: number;
  is_blocked?: boolean;
  blocked_reason?: string;
  rejection_reason?: string;
  published_days?: number | null;
}

function product(seed: ProductSeed): MockProduct {
  const status = seed.status ?? "ACTIVE";
  const createdDays = seed.published_days ?? 10;
  return {
    id: IDS.product(seed.index),
    seller_id: IDS.user(seed.seller),
    category_id: IDS.category(seed.category),
    title: seed.title,
    description: seed.description,
    price: seed.price,
    condition: seed.condition,
    usage_months: seed.usage ?? null,
    province_code: seed.province,
    delivery_method: seed.method,
    shipping_fee: seed.method === "MEETUP" ? "0" : (seed.fee ?? "0"),
    status,
    version: 1,
    is_blocked: seed.is_blocked ?? false,
    block_reason: seed.blocked_reason ?? null,
    rejection_reason: seed.rejection_reason ?? null,
    reserved_order_id: null,
    published_at: seed.published_days === null ? null : daysAgo(createdDays),
    deleted_at: null,
    created_at: daysAgo(createdDays),
    updated_at: daysAgo(Math.max(0, createdDays - 1)),
    images: imageSet(seed.index, seed.title, seed.images ?? 2),
  };
}

